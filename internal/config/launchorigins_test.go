package config

// launchorigins_test.go pins launchorigins.go: a refusal in a jail about a key of a config the
// launch handed it — the generated user scope, or the assembled copy of the jail's own workspace
// — names the HOST file that set the key and says an edit takes effect at relaunch, instead of
// naming the generated copy (or nothing). Each case runs the host half (the loader with its
// record, the render or the write), then the jail half (the loader a jail's `yolo check` or
// launch reads, ValidateConfig, Annotate).

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// The models file is an include of the user config: host-only, never mounted into a jail.
const wireIDModels = "{\n  \"providers\": {\"kilo\": {\"models\": {\"default\": {\"id\": \"m\", \"wireId\": \"w\"}}}}\n}"

const relaunchNote = "; this jail reads a copy made at launch, so an edit there takes effect when the jail is relaunched)"

// hostWithWireIDInclude writes a host home whose user config includes models.jsonc, the file
// that sets the refused key.
func hostWithWireIDInclude(t *testing.T) {
	t.Helper()
	_, dir := sourcesHome(t)
	write(t, filepath.Join(dir, "config.jsonc"), `{"include_if_found": ["models.jsonc"]}`)
	write(t, filepath.Join(dir, "models.jsonc"), wireIDModels)
}

func TestARefusalInAJailNamesTheHostFileThatSetTheKey(t *testing.T) {
	// The host half: the launch's composition, filtered and rendered with its record.
	hostWithWireIDInclude(t)
	effective, src, err := LoadConfigWithoutWorkspaceFileWithSources(t.TempDir(), false, discard)
	if err != nil || src == nil {
		t.Fatalf("host load: %v (record %v)", err, src)
	}
	filtered, _ := FilterInherit(effective, InheritPreflight)
	body, err := RenderFilteredWithOrigins(filtered, src, InheritPreflight, "")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(body, "\n"+originsLinePrefix) {
		t.Fatalf("the generated file carries no launch origins:\n%s", body)
	}

	// The jail half: that file IS the jail's user config.
	_, jailDir := sourcesHome(t)
	write(t, filepath.Join(jailDir, "config.jsonc"), body)
	t.Setenv("YOLO_VERSION", "9.9.9")
	cfg, jsrc, err := UserScopeConfigWithSources(true, discard)
	if err != nil {
		t.Fatal(err)
	}
	errs, _ := ValidateConfig(cfg, t.TempDir(), nil)
	got := line(t, jsrc.Annotate(errs), "wireId: unknown key")
	want := "config.providers.kilo.models.default.wireId: unknown key"
	if !strings.HasPrefix(got, want) ||
		!strings.HasSuffix(got, " (set in ~/.config/yolo-jail/models.jsonc on the host"+relaunchNote) {
		t.Errorf("got  %s\nwant %q … naming ~/.config/yolo-jail/models.jsonc on the host and the relaunch", got, want)
	}

	// The record is believed only in a jail: on a host the same bytes are an ordinary file.
	t.Setenv("YOLO_VERSION", "")
	_, hsrc, err := UserScopeConfigWithSources(true, discard)
	if err != nil {
		t.Fatal(err)
	}
	if got := hsrc.AnnotateOne(want); !strings.HasPrefix(got, "~/.config/yolo-jail/config.jsonc:") {
		t.Errorf("on a host the generated bytes must be located as the file itself: %s", got)
	}
}

// The assembled copy LoadConfig reads back for the jail's own workspace names the host file
// too, from the record the launch writes beside it — the per-workspace and workspace layers
// included, since the copy is the whole merge.
func TestARefusalAboutTheAssembledCopyNamesTheHostFile(t *testing.T) {
	hostWithWireIDInclude(t)
	ws, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	merged, src, err := LoadConfigWithSources(ws, false, discard)
	if err != nil || src == nil {
		t.Fatalf("host load: %v (record %v)", err, src)
	}
	if err := WriteAssembledConfig(ws, merged); err != nil {
		t.Fatal(err)
	}
	if err := WriteAssembledOrigins(ws, merged, src); err != nil {
		t.Fatal(err)
	}

	// In the jail, with no user config of its own: the copy is all it has.
	sourcesHome(t)
	t.Setenv("YOLO_VERSION", "9.9.9")
	t.Setenv("YOLO_WORKSPACE", ws)
	cfg, jsrc, err := LoadConfigWithSources(ws, false, discard)
	if err != nil {
		t.Fatal(err)
	}
	if jsrc == nil {
		t.Fatal("the jail's own-workspace read returned no record beside the assembled copy")
	}
	errs, _ := ValidateConfig(cfg, ws, nil)
	got := line(t, jsrc.Annotate(errs), "wireId: unknown key")
	if !strings.HasSuffix(got, " (set in ~/.config/yolo-jail/models.jsonc on the host"+relaunchNote) {
		t.Errorf("got %s", got)
	}

	// A copy rewritten without a record (an older launcher) is not described by the old record.
	if err := WriteAssembledConfig(ws, decode(t, `{"packages": ["jq"]}`)); err != nil {
		t.Fatal(err)
	}
	if _, jsrc, _ := LoadConfigWithSources(ws, false, discard); jsrc != nil {
		t.Errorf("a record of another copy still located this one: %v", jsrc.Locations("config.packages"))
	}
	if err := WriteAssembledConfig(ws, merged); err != nil {
		t.Fatal(err)
	}

	// A launch that records nothing (a sealed one) overwrites the record, so no earlier
	// launch's record describes it.
	if err := WriteAssembledOrigins(ws, merged, nil); err != nil {
		t.Fatal(err)
	}
	if _, jsrc, _ := LoadConfigWithSources(ws, false, discard); jsrc != nil {
		t.Errorf("an empty record still located the copy: %v", jsrc.Locations("config.providers"))
	}
}

// A workspace file is never read as a launch copy, whatever line it carries: the workspace is the
// jail's to write, and its own files are located as themselves.
func TestAWorkspaceFileIsNeverReadAsALaunchCopy(t *testing.T) {
	sourcesHome(t)
	t.Setenv("YOLO_VERSION", "9.9.9")
	ws := t.TempDir()
	t.Setenv("YOLO_WORKSPACE", filepath.Join(ws, "elsewhere")) // not this jail's own workspace
	write(t, filepath.Join(ws, WorkspaceConfigName),
		originsLinePrefix+`{"w":["~/somewhere/else.jsonc"]}`+"\n{\n  \"kvm\": \"yes\"\n}")
	if err := os.MkdirAll(filepath.Join(ws, "elsewhere"), 0o755); err != nil {
		t.Fatal(err)
	}
	_, src, err := LoadConfigWithSources(ws, false, discard)
	if err != nil {
		t.Fatal(err)
	}
	if got := src.AnnotateOne("config.kvm: expected a boolean"); !strings.HasPrefix(got, WorkspaceConfigName+":3:") &&
		!strings.Contains(got, "/"+WorkspaceConfigName+":3:") {
		t.Errorf("a workspace file was located by a line it carries: %s", got)
	}
}
